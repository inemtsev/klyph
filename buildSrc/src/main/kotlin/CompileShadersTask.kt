import java.io.File
import java.util.Base64
import javax.inject.Inject
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.process.ExecOperations

/**
 * Compiles HLSL shaders with SDL_shadercross into MSL, SPIR-V and DXIL and writes one Kotlin file
 * that embeds every result as a `CompiledShader`. The file is checked in, so machines without the
 * tool still build; run the task to refresh it after editing a shader.
 *
 * Source files are named `<name>.vert.hlsl` or `<name>.frag.hlsl`; the stage comes from the name.
 */
abstract class CompileShadersTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    /** Path of the shadercross executable. */
    @get:Input
    abstract val tool: Property<String>

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputFile
    abstract val output: RegularFileProperty

    /** Scratch folder for the compiler's output files. */
    @get:Internal
    abstract val workDir: DirectoryProperty

    @get:Inject
    abstract val exec: ExecOperations

    @TaskAction
    fun compile() {
        val work = workDir.get().asFile.apply { mkdirs() }
        val shaders = sources.files.sortedBy { it.name }.map { compileOne(it, work) }
        val text = buildString {
            appendLine("// Generated by :klyph:compileShaders from src/shaders/*.hlsl. Do not edit; edit the HLSL and rerun the task.")
            appendLine("@file:Suppress(\"ktlint\", \"MaxLineLength\")")
            appendLine()
            appendLine("package ${packageName.get()}")
            appendLine()
            appendLine("import klyph.platform.CompiledShader")
            appendLine("import klyph.platform.ShaderStage")
            for (shader in shaders) {
                appendLine()
                appendLine("/** Compiled from `src/shaders/${shader.sourceName}`. */")
                appendLine("internal val ${shader.kotlinName}: CompiledShader = CompiledShader(")
                appendLine("    stage = ShaderStage.${shader.stage},")
                appendLine("    msl = \"\"\"${shader.msl.replace("\$", "\${'\$'}")}\"\"\",")
                appendLine("    spirvBase64 = \"${shader.spirv}\",")
                appendLine("    dxilBase64 = \"${shader.dxil}\",")
                appendLine("    samplers = ${shader.samplers},")
                appendLine("    storageTextures = ${shader.storageTextures},")
                appendLine("    storageBuffers = ${shader.storageBuffers},")
                appendLine("    uniformBuffers = ${shader.uniformBuffers},")
                appendLine(")")
            }
        }
        output.get().asFile.apply { parentFile.mkdirs() }.writeText(text)
    }

    private class Compiled(
        val sourceName: String,
        val kotlinName: String,
        val stage: String,
        val msl: String,
        val spirv: String,
        val dxil: String,
        val samplers: Int,
        val storageTextures: Int,
        val storageBuffers: Int,
        val uniformBuffers: Int,
    )

    private fun compileOne(source: File, work: File): Compiled {
        val parts = source.name.removeSuffix(".hlsl").split('.')
        require(parts.size == 2 && parts[1] in setOf("vert", "frag")) {
            "Shader ${source.name} must be named <name>.vert.hlsl or <name>.frag.hlsl."
        }
        val stage = if (parts[1] == "vert") "VERTEX" else "FRAGMENT"
        val stageFlag = if (parts[1] == "vert") "vertex" else "fragment"
        fun run(destination: String, extension: String): File {
            val out = File(work, "${parts[0]}.${parts[1]}.$extension")
            val result = exec.exec {
                commandLine(tool.get(), source.absolutePath, "-s", "HLSL", "-d", destination, "-t", stageFlag, "-o", out.absolutePath)
                isIgnoreExitValue = true
            }
            if (result.exitValue != 0) throw GradleException("shadercross failed on ${source.name} for $destination (exit ${result.exitValue}).")
            return out
        }
        val msl = run("MSL", "msl").readText()
        val spirv = Base64.getEncoder().encodeToString(run("SPIRV", "spv").readBytes())
        val dxil = Base64.getEncoder().encodeToString(run("DXIL", "dxil").readBytes())
        val json = run("JSON", "json").readText()
        fun count(key: String): Int = Regex("\"$key\"\\s*:\\s*(\\d+)").find(json)?.groupValues?.get(1)?.toInt()
            ?: throw GradleException("shadercross JSON for ${source.name} has no \"$key\".")
        val kotlinName = parts[0].replaceFirstChar { it.uppercase() } + (if (stage == "VERTEX") "Vertex" else "Fragment") + "Shader"
        return Compiled(
            sourceName = source.name,
            kotlinName = kotlinName,
            stage = stage,
            msl = msl,
            spirv = spirv,
            dxil = dxil,
            samplers = count("samplers"),
            storageTextures = count("storage_textures"),
            storageBuffers = count("storage_buffers"),
            uniformBuffers = count("uniform_buffers"),
        )
    }
}
